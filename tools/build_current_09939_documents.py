paragraph(main, "Several PLS formulations address different computational and statistical settings. PLS-SVD derives directions from a singular value decomposition of the predictor-response cross-covariance, whereas SIMPLS extracts sequential components while preserving a deflation geometry in the original variable space [3]. Orthogonal PLS separates response-orthogonal variation [4], and kernel PLS permits nonlinear relations through a kernel representation [5]. The R package pls provides established implementations [6], while IKPLS supplies NumPy- and JAX-based improved-kernel PLS algorithms for CPU and GPU computation [7].")
paragraph(main, "For large matrices, the dominant directions can be approximated without a complete singular value decomposition. Randomized SVD (rSVD) constructs a low-dimensional range approximation and can replace expensive dense decompositions when the leading subspace is sufficiently separated [8]. Its approximation depends on rank, oversampling, power iterations, conditioning and seed; therefore, computational gains must be interpreted together with numerical diagnostics.")
