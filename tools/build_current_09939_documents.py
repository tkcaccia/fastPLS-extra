def rows(name: str) -> list[dict[str, str]]:
    path = TAB / name
    if not path.exists():
        raise FileNotFoundError(f"Missing current evidence: {path}")
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def number(value: str | float | int | None) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return math.nan


def fmt(value: str | float | int | None, digits: int = 3) -> str:
    val = number(value)
    if not math.isfinite(val):
        return "NA"
    return f"{val:.{digits}f}"


def add_line_numbers(section) -> None:
    sect_pr = section._sectPr
    old = sect_pr.find(qn("w:lnNumType"))
    if old is not None:
        sect_pr.remove(old)
    node = OxmlElement("w:lnNumType")
    node.set(qn("w:countBy"), "1")
    node.set(qn("w:restart"), "continuous")
    node.set(qn("w:distance"), "360")
    sect_pr.append(node)


def configure(doc: Document, supplement: bool = False) -> None:
    section = doc.sections[0]
    section.orientation = WD_ORIENT.PORTRAIT
    section.page_width = Inches(8.27)
    section.page_height = Inches(11.69)
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)
    section.left_margin = Inches(0.75 if supplement else 0.85)
    section.right_margin = Inches(0.65 if supplement else 0.75)
    add_line_numbers(section)

    normal = doc.styles["Normal"]
    normal.font.name = "Arial"
    normal.font.size = Pt(9.5 if supplement else 10)
    normal.font.color.rgb = RGBColor(0, 0, 0)
    normal.paragraph_format.space_after = Pt(3)
    normal.paragraph_format.line_spacing = 1.08
    for name, size in (("Title", 17), ("Heading 1", 13), ("Heading 2", 11)):
        style = doc.styles[name]
        style.font.name = "Arial"
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = RGBColor(0, 0, 0)


def set_cell_shading(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shading = tc_pr.find(qn("w:shd"))
    if shading is None:
        shading = OxmlElement("w:shd")
        tc_pr.append(shading)
    shading.set(qn("w:fill"), fill)


def set_cell_margins(cell, top: int = 55, start: int = 65,
                     bottom: int = 55, end: int = 65) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    margins = tc_pr.first_child_found_in("w:tcMar")
    if margins is None:
        margins = OxmlElement("w:tcMar")
        tc_pr.append(margins)
    for name, value in (("top", top), ("start", start),
                        ("bottom", bottom), ("end", end)):
        node = margins.find(qn(f"w:{name}"))
        if node is None:
            node = OxmlElement(f"w:{name}")
            margins.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def keep_table_row_together(row, repeat_header: bool = False) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    cant_split = OxmlElement("w:cantSplit")
    tr_pr.append(cant_split)
    if repeat_header:
        header = OxmlElement("w:tblHeader")
        header.set(qn("w:val"), "true")
        tr_pr.append(header)


def paragraph(doc: Document, text: str, bold_prefix: str | None = None):
    par = doc.add_paragraph()
    if bold_prefix and text.startswith(bold_prefix):
        par.add_run(bold_prefix).bold = True
        par.add_run(text[len(bold_prefix):])
    else:
        par.add_run(text)
    return par


def heading(doc: Document, text: str, level: int = 1):
    return doc.add_heading(text, level=level)


def add_table(doc: Document, caption: str, headers: list[str], body: list[list[str]],
              font_size: float = 7.2) -> None:
    cap = doc.add_paragraph()
    cap.add_run(caption).bold = True
    cap.paragraph_format.keep_with_next = True
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    for j, value in enumerate(headers):
        table.rows[0].cells[j].text = value
    for values in body:
        cells = table.add_row().cells
        for j, value in enumerate(values):
            cells[j].text = str(value)
    keep_table_row_together(table.rows[0], repeat_header=True)
    for i, row in enumerate(table.rows):
        if i > 0:
            keep_table_row_together(row)
        for cell in row.cells:
            cell.vertical_alignment = 1
            set_cell_margins(cell)
            if i == 0:
                set_cell_shading(cell, "D9E2F3")
            elif i % 2 == 0:
                set_cell_shading(cell, "F6F8FA")
            for par in cell.paragraphs:
                par.paragraph_format.space_after = Pt(0)
                par.paragraph_format.line_spacing = 1.0
                for run in par.runs:
                    run.font.name = "Arial"
                    run.font.size = Pt(font_size)
                    if i == 0:
                        run.bold = True


def add_figure(doc: Document, filename: str, caption: str, width: float) -> None:
    path = FIG / filename
