heading(main, "2.2 rSVD, precision and backends", 2)
paragraph(main, "The public low-rank solver is rSVD. Automatic controls use profile-specific oversampling and power iterations: the ordinary profile uses 32 and 5, high-response and sparse-high-class profiles use 48/6 or 64/7, and the massive-cross-covariance SIMPLS profile uses 12/2. The effective controls, seed, executed estimator and numerical status are retained internally for diagnostics. Approximate results are not described as exact equivalence to a dense decomposition.")
paragraph(main, "CPU routes are compiled C++ and call the linked BLAS/LAPACK; multicore execution is available only when the linked numerical library and operation use multiple threads. CUDA routes use NVIDIA cuBLAS, cuSOLVER and cuRAND for device matrix products, factorizations and randomized sketches [11]. Metal float32 routes use Apple Metal Performance Shaders and custom Metal kernels [12]. CUDA PLS-SVD and SIMPLS retain fitting and prediction on the device where supported. Public Metal execution is route-dependent: matrix products and compact prediction use Metal, while component extraction can be hybrid or host-assisted according to the matrix regime; Metal LDA uses the compiled CPU float32 discriminant solver after Metal score projection. OPLS and nonlinear-kernel accelerator routes retain host preprocessing or Gram-matrix stages. Unsupported accelerator or precision combinations return an error rather than silently falling back to CPU.")
paragraph(main, "R stores ordinary numeric matrices in float64. Inputs created with the float package occupy float32 storage and automatically select a supported float32 numerical route. This can reduce the size of input and intermediate arrays, but complete-process memory and runtime also include the R session, loaded data, libraries, allocator state and device context. Precision comparisons consequently report measured memory and prediction differences rather than inferring a twofold process-memory reduction.")

heading(main, "2.3 Classification, regression and validation", 2)
paragraph(main, "For classification, argmax returns the largest predicted dummy-response score. LDA is fitted to retained PLS scores. The pooled within-class covariance is computed as [TᵀT − Σⱼ nⱼμⱼμⱼᵀ]/max(1,n−J), without materializing centred class blocks. Regularized systems are solved by Cholesky factorization and triangular solves. The deterministic scale-normalized fallback tests ρ = 10⁻⁸, 10⁻⁶, 10⁻⁵, 10⁻⁴, 10⁻³ and 10⁻² and uses the first successful factorization. The discriminant is δⱼ(t) = tᵀwⱼ − 0.5 μⱼᵀwⱼ + log(nⱼ/n).")
paragraph(main, "The compiled single and double cross-validation procedures preserve groups supplied through constrain, preventing observations from one subject from entering both training and validation folds. Component number and prediction-relevant model arguments can be selected using accuracy, balanced accuracy, RMSD or Q² as appropriate. Training R², independent-test Q² relative to the training mean and fold-based cross-validated Q² are returned as distinct quantities. Permutation p-values use the finite-sample correction (b + 1)/(B + 1); when groups are supplied, labels are permuted at the exchangeability-block level.")

