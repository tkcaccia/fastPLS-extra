heading(main, "2.2 rSVD and computational backends", 2)
paragraph(main, "The public low-rank solver is rSVD. Automatic controls use profile-specific oversampling and power iterations: the ordinary profile uses 32 and 5, high-response and sparse-high-class profiles use 48/6 or 64/7, and the massive-cross-covariance SIMPLS profile uses 12/1. The effective controls, seed, executed estimator and numerical status are retained internally for diagnostics. Approximate results are not described as exact equivalence to a dense decomposition.")
paragraph(main, "CPU routes are compiled C++ and call the linked BLAS/LAPACK; multicore execution is available only when the linked numerical library and operation use multiple threads. CUDA routes use NVIDIA cuBLAS, cuSOLVER and cuRAND for device matrix products, factorizations and randomized sketches [11]. After input transfer, CUDA retains preprocessing, decomposition, SIMPLS updates, OPLS filtering, nonlinear-kernel construction and centering, prediction and LDA on the device in float32 and float64. The Apple route instead uses a fixed operation split: persistent Metal Performance Shaders and custom kernels evaluate fitting products involving the training sample matrix, whereas the CPU performs centering and scaling, reduced QR/SVD calculations, sequential orthogonalization and deflation, coefficient assembly, LDA and compact prediction [12]. This assignment is invariant to dataset shape. Metal accepts float32 because the tested Apple GPU does not provide the float64 arithmetic required by the kernels. Unsupported accelerator or precision combinations return an error rather than silently falling back to CPU.")
