heading(main, "4. Discussion")
paragraph(main, "fastPLS accelerates SIMPLS through execution and storage choices rather than redefining the underlying sequential PLS objective. Reusing deflation products and workspaces reduces repeated allocation, while compact latent prediction avoids dense p by q coefficient arrays for every requested prefix. Label-aware products are particularly helpful in multiclass problems because the response cross-product can be formed from class sums without materializing a dense n by J indicator matrix. These gains explain why the current single-CPU workflow was fastest or tied on most completed classification datasets, while the remaining small task showed that package overhead can dominate when all methods finish in hundredths of a second.")
paragraph(main, "The choice between PLS-SVD and SIMPLS depends on the scientific and matrix regime. PLS-SVD obtains a retained subspace in one decomposition and was faster for the extreme-response NMR workload, but its component count is response-rank limited. SIMPLS pays for sequential orthogonalization and deflation, yet can continue beyond a low response rank and supports an interpretable component path. Compact prediction matters most when p, q, the test size or the number of requested prefixes makes dense prediction storage large. Matrix-free cross-covariance is valuable when p q storage is prohibitive; otherwise, materializing S can be faster because it avoids repeated passes through X and Y.")
paragraph(main, "rSVD is retained as the primary solver because it enables the observed large-scale execution, but it is an approximation rather than an exact replacement for every spectrum or conditioning regime. Automatic profiles increase oversampling and power iterations outside the massive-cross-covariance route, and the fit records the effective settings and numerical status. Users conducting confirmatory biomedical analyses should examine stability across seeds and compare predictions or selected components when the singular spectrum is poorly separated. Reaching a component-grid boundary should trigger extension of the training-only grid or cautious reporting as the best tested value.")
paragraph(main, "GPU use is not automatically advantageous. CUDA became useful when dense products or response dimensions were large enough to amortize transfer and context costs; matched NMR SIMPLS was substantially faster on CUDA than on the paired Linux CPU, while most small tasks remained CPU-favourable. On Apple silicon, full device residency was not retained because sequential reduced decompositions and component updates were more efficient through Apple Accelerate. The public Metal route therefore assigns fitting products involving the training sample matrix to persistent Metal workspaces and keeps reduced factorizations, sequential orthogonalization, deflation, coefficient assembly, LDA and compact prediction on the CPU. This operation assignment is fixed across datasets and preserves the same PLS calculation; it is not a shape-based choice of whole-model backend. CUDA OPLS and nonlinear-kernel routes remain device-native in float32 and float64; Metal routes use the documented CPU/Metal split in float32. Unsupported accelerator requests return an error rather than invoking a hidden CPU fallback. Nonlinear kernels remain practically limited by O(n²) Gram-matrix storage.")
paragraph(main, "float32 reduces the representation size of input and many intermediates, which was essential for the million-row and extreme-response workflows, but it is not a universal speed or process-memory guarantee. The current NMR results show small route-dependent metric differences, and complete-process RSS includes data, runtime libraries and allocator state. Precision should therefore be selected according to feasibility and verified numerical behaviour rather than assumed superiority.")
paragraph(main, "The study has limitations. Fixed prepared splits primarily support paired computational comparison and do not replace subject-grouped external validation. The broad independent-software panel is an end-to-end workflow comparison with different native precisions and model objects. Accelerator ratios depend on two workstations and include initialization overhead. The ImageNet experiment is an engineering analogue for foundation-model embeddings, not biomedical evidence. Future work will expand validation on other GPU architectures, strengthen route-specific numerical diagnostics and refine automatic dispatch using controlled multi-factor scaling experiments.")

heading(main, "5. Conclusions")
paragraph(main, "fastPLS combines a compiled sequential SIMPLS path with compact prediction, rSVD and optional CUDA and Metal execution. It extends practical PLS analysis to response and sample dimensions that were previously difficult to process in R, while preserving explicit reporting of precision, backend residency and numerical controls. The NMR application demonstrates the value of the implementation for high-response biomedical prediction; appropriate solver and backend choices remain workload dependent.")

